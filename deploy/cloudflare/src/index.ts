type ContainerEnvName = (typeof CONTAINER_ENV)[number];

// `Env` (the APP binding) comes from worker-configuration.d.ts, generated by
// `npm run types`; secrets are untyped there because they are not in wrangler.jsonc.
type AppEnv = Env & Partial<Record<ContainerEnvName, string>>;

export class AwesomeVideoApp extends Container<AppEnv> {
  defaultPort = 5000;
  sleepAfter = "1h";
  enableInternet = true;

  constructor(ctx: ConstructorParameters<typeof Container<AppEnv>>[0], env: AppEnv) {
    super(ctx, env);
    const forwarded: Record<string, string> = {};
    for (const name of CONTAINER_ENV) {
      const value = env[name];
      if (typeof value === "string" && value !== "") forwarded[name] = value;
    }
    this.envVars = {
      ...forwarded,
      NODE_ENV: "production",
      PORT: "5000",
      DISABLE_BACKGROUND_JOBS: "1",
      PUBLIC_SITE_URL: "https://awesome.video",
    };
  }
}

// The container reaches the internet from inside Cloudflare's network. If the
// edge's cf-* / cdn-loop headers ride along to another Cloudflare-proxied host
// (the app's Clerk Frontend API proxy forwards request headers verbatim), that
// host rejects the request with Error 1000 "DNS points to prohibited IP". Drop
// them here and hand the app the standard forwarding headers instead.
function forContainer(request: Request): Request {
  const url = new URL(request.url);
  const headers = new Headers();
  for (const [key, value] of request.headers) {
    const name = key.toLowerCase();
    if (name.startsWith("cf-") || name === "cdn-loop") continue;
    headers.append(key, value);
  }
  const clientIp = request.headers.get("cf-connecting-ip");
  if (clientIp) headers.set("x-forwarded-for", clientIp);
  headers.set("x-forwarded-proto", url.protocol.replace(":", ""));
  headers.set("x-forwarded-host", url.host);
  return new Request(request, { headers });
}

export default {
  fetch(request: Request, env: AppEnv): Promise<Response> {
    return getContainer(env.APP).fetch(forContainer(request));
  },
} satisfies ExportedHandler<AppEnv>;
